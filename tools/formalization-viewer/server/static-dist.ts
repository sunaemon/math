import { preloadViewerModules } from "./module-preload.ts";
import { ensureSearchIndex } from "./search-index.ts";
import { bookReferences } from "./references.ts";
import { fixedMath } from "./mathml.ts";
import { bookDefinitionRegistry } from "./definitions.ts";
// Build a static distribution of the formalization viewer under <root>/dist.
//
// Only BOOKLINK_PROJECT is exported; direct invocation without it selects the
// first discovered manifest. Other projects are not included as extra mounts.
// The dist directory mirrors the URL space of serve.ts, so serving it with any
// static file server reproduces the live viewer, minus the Lean LSP bridge and
// the file watcher:
//
//   <dist>/<mount>/...   one URL tree holding the viewer assets, manifest.json
//                        (with "static": true so the browser uses the LSP cache
//                        instead of the /lsp bridge), the project files the live
//                        server allowlists, and the pregenerated lsp-cache/
//                        and highlight-cache/
//   <dist>/index.html    redirect to the mount
//
// The LSP cache is generated by lsp-cache.ts into the project build directory
// (so it survives dist rebuilds and is reused incrementally) and copied in.
// `lake build` runs first so every Lean file elaborates from cached oleans.

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { readProject, walkFiles, type Manifest } from "./projects.ts";
import { chapterTitles } from "./chapter-titles.ts";
import { CliUsageError, optionValue } from "./cli-values.ts";
import { atomicWrite, resolvedDestination, assertSourceWithinRoot } from "./file-output.ts";
import { generate } from "./lsp-cache.ts";
import { generate as generateHighlights } from "./highlight-cache.ts";
import { repoVersion, attachLicenseText, appendVendorComponents, katexMacros, macrosTexPath } from "./repo-version.ts";

const VIEWER_DIR = "tools/formalization-viewer";
// Build-time-only subtrees of the viewer dir that must not ship in the dist:
// the TypeScript browser sources (only the transpiled build/ .js is shipped) and
// the Node server (the dist is served statically).
const VIEWER_EXCLUDE = new Set([
  "src",
  "server",
  "e2e",
  "fixtures",
  "tsconfig.json",
  "tsconfig.test.json",
  "check_highlights.mjs",
  "README.md",
]);

const REDIRECT_HTML = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <noscript><meta http-equiv="refresh" content="0; url={target}"></noscript>
  <title>formalization viewer</title>
</head>
<body><a href="{target}">formalization viewer</a>
<script>location.replace(document.querySelector('a').getAttribute('href') + location.search + location.hash);</script>
</body>
</html>
`;

function assetHash(p: string): string {
  return createHash("sha256").update(fs.readFileSync(p)).digest("hex").slice(0, 10);
}

// Append a content-hash `?v=` query to the viewer's own CSS/JS in index.html, so
// a rebuilt dist automatically busts any cached copy. Idempotent.
function stampAssetVersions(mountDir: string): void {
  const indexPath = path.join(mountDir, "index.html");
  if (!fs.existsSync(indexPath)) return;
  let html = preloadViewerModules(fs.readFileSync(indexPath, "utf-8"), mountDir);
  const assets: Record<string, string> = {
    "./build/styles.css": path.join(mountDir, "build", "styles.css"),
    "./build/app.js": path.join(mountDir, "build", "app.js"),
    "./build/view-bootstrap.js": path.join(mountDir, "build", "view-bootstrap.js"),
  };
  for (const [ref, p] of Object.entries(assets)) {
    if (!fs.existsSync(p)) continue;
    const version = assetHash(p);
    const escaped = ref.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    html = html.replace(new RegExp(`${escaped}(\\?v=[^"']*)?`, "g"), `${ref}?v=${version}`);
  }
  fs.writeFileSync(indexPath, html);
}

function loadProject(root: string): Manifest {
  const named = (process.env.BOOKLINK_PROJECT ?? "").trim();
  const candidates = named
    ? [named]
    : fs
        .readdirSync(root)
        .filter((entry) => {
          try {
            return fs.statSync(path.join(root, entry, "manifest.json")).isFile();
          } catch {
            return false;
          }
        })
        .sort();
  for (const dirname of candidates) {
    const p = path.join(root, dirname, "manifest.json");
    if (fs.existsSync(p) && fs.statSync(p).isFile()) {
      return readProject(root, dirname);
    }
  }
  throw new Error("No project manifest found (expected <dir>/manifest.json under the repo root).");
}

function copyServedFiles(root: string, project: Manifest, mountDir: string): number {
  const projectRoot = path.join(root, project.dir);
  const flat = new Set(project.flat ?? []);
  let copied = 0;
  for (const [sub, exts] of Object.entries(project.served ?? {})) {
    const allowed = new Set(exts.map((ext) => `.${ext}`));
    const srcDir = path.join(projectRoot, sub);
    try {
      if (!fs.statSync(srcDir).isDirectory()) continue;
    } catch {
      continue;
    }
    for (const src of walkFiles(srcDir)) {
      if (!allowed.has(path.extname(src))) continue;
      if (flat.has(sub) && path.dirname(src) !== srcDir) continue;
      assertSourceWithinRoot(root, src);
      const rel = path.relative(projectRoot, src);
      const dest = path.join(mountDir, rel);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(src, dest);
      copied += 1;
    }
  }
  return copied;
}

function mountPdfList(mountDir: string): string[] {
  const found = new Set<string>();
  for (const full of walkFiles(mountDir)) {
    if (full.toLowerCase().endsWith(".pdf")) {
      found.add(path.relative(mountDir, full).split(path.sep).join("/"));
    }
  }
  return [...found].sort();
}

const OUTPUT_MARKER = ".formalization-viewer-dist.json";

function isViewerOutput(dist: string): boolean {
  try {
    if (JSON.parse(fs.readFileSync(path.join(dist, OUTPUT_MARKER), "utf-8")).generator === "formalization-viewer")
      return true;
  } catch {
    /* Older distributions predate the explicit ownership marker. */
  }
  if (!fs.existsSync(path.join(dist, ".nojekyll"))) return false;
  for (const file of walkFiles(dist)) {
    if (path.basename(file) !== "manifest.json") continue;
    try {
      if (JSON.parse(fs.readFileSync(file, "utf-8")).static === true) return true;
    } catch {
      /* Not a viewer manifest. */
    }
  }
  return false;
}

export function assertDistDestination(root: string, dist: string): void {
  const canonicalRoot = fs.realpathSync(root);
  const relative = path.relative(canonicalRoot, resolvedDestination(dist));
  if (!relative || relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error("Distribution destination must be strictly inside the repository");
  }
  if ([".git", ".codex", ".claude", ".agents", ".aws"].includes(relative.split(path.sep)[0])) {
    throw new Error("Distribution destination cannot replace repository metadata");
  }
  if (fs.existsSync(dist)) {
    if (!fs.statSync(dist).isDirectory() || (fs.readdirSync(dist).length && !isViewerOutput(dist))) {
      throw new Error("Refusing to replace a non-viewer output directory");
    }
  }
}

interface DistArgs {
  root: string;
  dist: string | null;
  noLakeBuild: boolean;
  skipLspCache: boolean;
  skipHighlightCache: boolean;
}

export function parseArgs(argv: string[]): DistArgs {
  const args: DistArgs = { root: ".", dist: null, noLakeBuild: false, skipLspCache: false, skipHighlightCache: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--root") args.root = optionValue(argv, i++);
    else if (arg === "--dist") args.dist = optionValue(argv, i++);
    else if (arg === "--no-lake-build") args.noLakeBuild = true;
    else if (arg === "--skip-lsp-cache") args.skipLspCache = true;
    else if (arg === "--skip-highlight-cache") args.skipHighlightCache = true;
    else throw new CliUsageError(`Unknown option: ${arg}`);
  }
  return args;
}

export async function main(argv = process.argv.slice(2)): Promise<void> {
  const args = parseArgs(argv);
  const root = path.resolve(args.root);
  const project = loadProject(root);
  const projectDir = project.dir;
  const lspDir = project.lspDir ?? projectDir;
  const mount = project.mount.replace(/^\/+|\/+$/g, "");
  const dist = path.resolve(args.dist ?? path.join(root, "dist"));
  const cacheDir = path.join(root, projectDir, "build", "lsp-cache");
  const highlightDir = path.join(root, projectDir, "build", "highlight-cache");
  assertDistDestination(root, dist);
  process.stdout.write(`Static distribution: ${projectDir} (single-project export)\n`);

  if (!args.skipLspCache) {
    if (!args.noLakeBuild) {
      process.stdout.write("lsp-cache: running lake build...\n");
      execFileSync("lake", ["build"], { cwd: path.join(root, lspDir), stdio: "inherit" });
    }
    await generate(root, lspDir, cacheDir);
  }

  if (!args.skipHighlightCache) {
    const written = await generateHighlights(root, project, highlightDir);
    process.stdout.write(`highlight-cache: ${written} file(s) generated\n`);
  }

  assertDistDestination(root, dist);
  if (fs.existsSync(dist)) fs.rmSync(dist, { recursive: true, force: true });
  fs.mkdirSync(dist, { recursive: true });
  atomicWrite(path.join(dist, OUTPUT_MARKER), JSON.stringify({ generator: "formalization-viewer", version: 1 }));

  // Viewer assets live at the mount, exactly where applyMount routes them. The
  // TypeScript sources (src/) and the Node server (server/) are build-only.
  const mountDir = path.join(dist, mount);
  fs.cpSync(path.join(root, VIEWER_DIR), mountDir, {
    recursive: true,
    dereference: true,
    filter: (src) => {
      const rel = path.relative(path.join(root, VIEWER_DIR), src);
      const top = rel.split(path.sep)[0];
      if (VIEWER_EXCLUDE.has(top) || rel === path.join("vendor", "treesitter")) return false;
      assertSourceWithinRoot(root, src);
      return true;
    },
  });
  const catalog = path.join(root, VIEWER_DIR, "ai-catalog.json");
  if (fs.existsSync(catalog)) {
    fs.mkdirSync(path.join(dist, ".well-known"), { recursive: true });
    fs.copyFileSync(catalog, path.join(dist, ".well-known", "ai-catalog.json"));
  }
  const copied = copyServedFiles(root, project, mountDir);
  const searchIndex = await ensureSearchIndex(root, project);
  if (searchIndex) {
    fs.cpSync(searchIndex, path.join(mountDir, "pagefind"), { recursive: true });
    await (await import("pagefind")).close();
  }
  stampAssetVersions(mountDir);

  const staticManifest: Manifest = structuredClone(project);
  staticManifest.static = true;
  if (staticManifest.parallelPdf?.dir && staticManifest.parallelPdf.path) {
    const copyPeerFile = (sourcePath: string): string => {
      const source = path.join(root, staticManifest.parallelPdf!.dir!, sourcePath);
      assertSourceWithinRoot(root, source);
      const relative = path.join("parallel-pdf", path.basename(sourcePath));
      const destination = path.join(mountDir, relative);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.copyFileSync(source, destination);
      return relative;
    };
    const relative = copyPeerFile(staticManifest.parallelPdf.path);
    staticManifest.parallelPdf.mount = project.mount;
    staticManifest.parallelPdf.path = relative;
    if (staticManifest.parallelPdf.mapPath) {
      // The copy-TeX shortcut slices the peer map's texMatch spans out of the
      // peer debug tex, so bundle that tex alongside the map and record where
      // it landed — the live server serves it from the peer mount, but a
      // static dist has no peer mount to fall back to.
      const mapAbsolute = path.join(root, staticManifest.parallelPdf.dir, staticManifest.parallelPdf.mapPath);
      try {
        const peerMap = JSON.parse(fs.readFileSync(mapAbsolute, "utf8"));
        const texFile = typeof peerMap?.texFile === "string" ? peerMap.texFile : null;
        const texRelative = texFile ? path.relative(path.join(root, staticManifest.parallelPdf.dir), texFile) : null;
        if (texRelative && !texRelative.startsWith("..") && !path.isAbsolute(texRelative)) {
          staticManifest.parallelPdf.texPath = copyPeerFile(texRelative);
        }
      } catch {
        // No peer tex in the dist: the copy shortcut degrades to its
        // "peer TeX unavailable" feedback, same as a missing sourcemap.
      }
      staticManifest.parallelPdf.mapPath = copyPeerFile(staticManifest.parallelPdf.mapPath);
    }
  }
  staticManifest.version = repoVersion(root);
  if (staticManifest.license) {
    appendVendorComponents(root, staticManifest.license);
    staticManifest.license = attachLicenseText(root, staticManifest.license);
  }
  staticManifest.definitionRegistry = bookDefinitionRegistry(root, project);
  staticManifest.references = bookReferences(root, project);
  staticManifest.katexMacros = katexMacros(macrosTexPath(root, projectDir));
  staticManifest.fixedMath = fixedMath(
    root,
    path.join(project.dir, String(project.sourceMap)),
    staticManifest.katexMacros as Record<string, string>,
  );
  staticManifest.pdfs = mountPdfList(mountDir);
  staticManifest.chapterTitles = chapterTitles(root, project);
  fs.writeFileSync(path.join(mountDir, "manifest.json"), JSON.stringify(staticManifest, null, 2));

  if (fs.existsSync(cacheDir)) {
    fs.cpSync(cacheDir, path.join(mountDir, "lsp-cache"), { recursive: true });
  }
  if (fs.existsSync(highlightDir)) {
    fs.cpSync(highlightDir, path.join(mountDir, "highlight-cache"), { recursive: true });
  }

  fs.writeFileSync(path.join(dist, "index.html"), REDIRECT_HTML.replace(/\{target\}/g, `${mount}/`));
  // GitHub Pages serves the tree through Jekyll unless told not to.
  fs.writeFileSync(path.join(dist, ".nojekyll"), "");

  const relDist = path.relative(root, dist);
  const port = (process.env.BOOKLINK_VIEWER_PORT ?? "8000").trim() || "8000";
  process.stdout.write(`Static viewer: ${copied} project files + viewer assets in ${relDist}/\n`);
  process.stdout.write(`Standalone serve with: python3 -m http.server ${port} --bind 127.0.0.1 -d ${relDist}\n`);
  process.stdout.write(`Then open: http://127.0.0.1:${port}/${mount}/\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  void main().catch((error: Error) => {
    process.stderr.write(`static-dist: ${error.message}\n`);
    process.exitCode = error instanceof CliUsageError ? 2 : 1;
  });
}
