export type UILanguage = "en" | "ja";
export function preferredLanguage(languages: readonly string[]): UILanguage {
  for (const tag of languages) {
    const language = tag.toLowerCase().split(/[-_]/)[0];
    if (language === "ja" || language === "en") return language;
  }
  return "en";
}
export function uiLanguagePreference(): UILanguage | "auto" {
  try {
    const language = globalThis.localStorage?.getItem("formalization-viewer-ui-language");
    if (language === "en" || language === "ja") return language;
  } catch {
    /* Storage can be disabled. */
  }
  return "auto";
}

const preference = uiLanguagePreference();
export const uiLanguage =
  preference !== "auto"
    ? preference
    : preferredLanguage(
        typeof navigator === "undefined"
          ? []
          : navigator.languages?.length
            ? navigator.languages
            : [navigator.language],
      );
const catalog = new Map(
  messages.flatMap(
    ([en, ja]) =>
      [
        [en, [en, ja]],
        [ja, [en, ja]],
      ] as const,
  ),
);
export function hasTranslation(message: string): boolean {
  return catalog.has(message);
}

export function t(message: string, ...values: (string | number)[]): string {
  const pair = catalog.get(message);
  const translated = pair ? pair[uiLanguage === "ja" ? 1 : 0] : message;
  return translated.replace(/\{(\d+)\}/g, (token, index) => String(values[Number(index)] ?? token));
}

// Only explicitly marked static chrome is translated. Never walk book text,
// source panes, PDF text, quoted context, or chat messages.
export function localizeStaticUI(): void {
  document.documentElement.lang = uiLanguage;
  for (const node of document.querySelectorAll<HTMLElement>("[data-ui-text]"))
    if (node.textContent?.trim() === node.dataset.uiText) node.textContent = t(node.dataset.uiText!);
  for (const attr of ["title", "placeholder", "aria-label"])
    for (const node of document.querySelectorAll(`[data-ui-${attr}]`))
      if (node.getAttribute(attr) === node.getAttribute(`data-ui-${attr}`))
        node.setAttribute(attr, t(node.getAttribute(`data-ui-${attr}`)!));
}
