hasSourceVariable (Reference _ identity) = isNothing (bindingConstant identity)
hasSourceVariable (Macro _ op) = any hasSourceVariable op
hasSourceVariable (Scoped _ body) = hasSourceVariable body
hasSourceVariable (Parenthesized _ body) = hasSourceVariable body
hasSourceVariable (Scalar _ _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (Compare _ _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (Derived _ body) = hasSourceVariable body
hasSourceVariable (Comparisons values) = any hasSourceVariable values
hasSourceVariable (Conjunction _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (SingletonSet _ _ _ _ point) = hasSourceVariable point
hasSourceVariable (PropositionPair left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (MembershipEquality _ _ left middle domain) = any hasSourceVariable [left, middle, domain]
hasSourceVariable (InclusionMap _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable RangeFamily{} = True
hasSourceVariable DecreasingFamily{} = True
hasSourceVariable RepeatedBinary{} = True
hasSourceVariable (TypedRange _ _ function) = hasSourceVariable function
hasSourceVariable (Coerce _ _ point) = hasSourceVariable point
hasSourceVariable (TypedLambda _ _ _ _ _ body) = hasSourceVariable body
hasSourceVariable (Aggregate _ _ _ family) = hasSourceVariable family
hasSourceVariable (SetIdentity _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable MetricBoundedSet{} = True
hasSourceVariable ExistentialSetPredicate{} = True
hasSourceVariable GuardedSet{} = True
hasSourceVariable GeneratedUnion{} = True
hasSourceVariable (Negate _ _ body) = hasSourceVariable body
hasSourceVariable (Index _ _ _ function argument) = hasSourceVariable function || hasSourceVariable argument
hasSourceVariable (ShiftIndex _ _ body) = hasSourceVariable body
hasSourceVariable (NamedReference _ _ _ identity) = isNothing (bindingConstant identity)
hasSourceVariable (Application _ _ _ function arguments) = hasSourceVariable function || any hasSourceVariable arguments
hasSourceVariable (MetricApplication _ _ _ _ _ metric left right) = any hasSourceVariable [metric, left, right]
hasSourceVariable (SubtypeRange _ _ _ function predicate) = hasSourceVariable function || hasSourceVariable predicate
hasSourceVariable (SubtypeApplication _ _ _ function argument) = hasSourceVariable function || hasSourceVariable argument
hasSourceVariable (UniversalSet _ carrier) = hasSourceVariable carrier
hasSourceVariable (SetExpression _ _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (EmbeddedRationalComplement _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (Lambda _ _ _ body) = hasSourceVariable body
hasSourceVariable (DefiningEquality _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (EmptySet _ ambient) = hasSourceVariable ambient
hasSourceVariable (UpperRay _ _ _ endpoint _) = hasSourceVariable endpoint
hasSourceVariable (IntegerCast _ body) = hasSourceVariable body
hasSourceVariable (IntegerNegate _ _ body) = hasSourceVariable body
hasSourceVariable (RealIntegerPower _ _ base powerIndex) = hasSourceVariable base || hasSourceVariable powerIndex
hasSourceVariable (RealSequenceSpace _ _ _ powerIndex) = hasSourceVariable powerIndex
hasSourceVariable (FunctionType _ _ _ domain codomain) = hasSourceVariable domain || hasSourceVariable codomain
hasSourceVariable (TypeDeclaration _ _ ty function) = hasSourceVariable ty || hasSourceVariable function
hasSourceVariable (HomeomorphismType _ _ left right) = hasSourceVariable left || hasSourceVariable right
hasSourceVariable (NonemptyType _ _ ty) = hasSourceVariable ty
hasSourceVariable (FiniteIndex _ dimension) = hasSourceVariable dimension
hasSourceVariable (CoordinateSpace _ _ _ alphabet index) = hasSourceVariable alphabet || hasSourceVariable index
hasSourceVariable (SubtypeType _ _ _ predicate) = hasSourceVariable predicate
hasSourceVariable (TypedMapForall _ _ _ domain body) = hasSourceVariable domain || hasSourceVariable body
hasSourceVariable (MultipleCalls body) = hasSourceVariable body
hasSourceVariable (FamilyLambda _ _ _ body) = hasSourceVariable body
hasSourceVariable (DependentSum _ _ family) = hasSourceVariable family
hasSourceVariable (IndexedSet _ _ _ _ family) = hasSourceVariable family
hasSourceVariable (RepeatedTuple _ _ witness points) = hasSourceVariable witness || any hasSourceVariable points
hasSourceVariable (Literal _ _ (SequenceLiteral (SequenceWitness _ body)) _) = hasSourceVariable body
hasSourceVariable (ConvergenceSequence _ (SequenceWitness _ body) limit) = hasSourceVariable body || hasSourceVariable limit
