newtype Candidate a = Candidate a
newtype Reviewed a = Reviewed a

-- All three parts must come from the existing review workflow. A successful
-- probe does not constitute a review basis. The caller computes current hashes.
data ReviewBasis = ReviewBasis
  { sourceFingerprint :: Text
  , rulesFingerprint :: Text
  , leanFingerprints :: Map Text Text
  }
  deriving (Eq, Show)

candidate :: a -> Candidate a
candidate = Candidate

review :: ReviewBasis -> ReviewBasis -> Candidate a -> Either String (Reviewed a)
review recorded current (Candidate expression)
  | recorded == current = Right (Reviewed expression)
  | otherwise = Left "Source, rules or Lean evidence changed since interpretation review"

reviewedExpression :: Reviewed a -> a
reviewedExpression (Reviewed expression) = expression

-- Candidate rendering is for probes only; it never returns a Reviewed value.
renderCandidate :: Candidate Expr -> Text
renderCandidate (Candidate expression) = render expression

renderReviewed :: Reviewed Expr -> Text
renderReviewed = render . reviewedExpression

render :: Expr -> Text
render = ordinaryTerm . renderPair [] 0 . candidate

operation :: Text -> [a] -> Either String (Operation a)
operation "SetDifference" [a, b] = Right (Difference a b)
operation "frac" [a, b] = Right (Fraction a b)
operation "Abs" [a] = Right (Absolute a)
operation "Closure" [a] = Right (Closure a)
operation "AmbientClosure" [a, b] = Right (AmbientClosure a b)
operation "Ball" [a, b] = Right (Ball a b)
operation "ClosedInterval" [a, b] = Right (ClosedInterval a b)
operation "OpenInterval" [a, b] = Right (OpenInterval a b)
operation "LeftClosedInterval" [a, b] = Right (LeftClosedInterval a b)
operation name _ = Left ("Unknown macro or invalid arity: " <> T.unpack name)

renderOperation :: Operation Text -> Text
renderOperation (Difference a b) = "(" <> a <> " \\ " <> b <> ")"
renderOperation (Fraction a b) = "((" <> a <> ") / (" <> b <> "))"
renderOperation (Absolute a) = "|" <> a <> "|"
renderOperation (Closure a) = "closure (" <> a <> ")"
renderOperation (AmbientClosure a b) = "@closure (" <> a <> ") inferInstance (" <> b <> ")"
renderOperation (Ball a b) = "Metric.ball (" <> a <> ") (" <> b <> " : ℝ)"
renderOperation (ClosedInterval a b) = interval "Set.Icc" a b
renderOperation (OpenInterval a b) = interval "Set.Ioo" a b
renderOperation (LeftClosedInterval a b) = interval "Set.Ico" a b

interval :: Text -> Text -> Text -> Text
interval headName a b = headName <> " (" <> a <> " : ℝ) (" <> b <> " : ℝ)"

