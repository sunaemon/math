referenceExpectations :: Text -> [Expr] -> [Rendered] -> [Pair]
referenceExpectations rule (Reference _ identity : _) _
  | rule `elem` ["index:subscript", "index:superscript"] =
      [if isNothing (bindingConstant identity) then "expectedVariable" .= bindingName identity else "expectedConstant" .= bindingName identity]
        <> maybe [] (\origin -> ["lowering" .= object ["kind" .= ("natural-index-origin" :: Text), "sourceOrigin" .= origin, "targetOrigin" .= (0 :: Int)]]) (bindingIndexOrigin identity)
referenceExpectations rule (Index{} : _) (callee : _) | rule `elem` ["index:subscript", "index:superscript"] = ["expectedCallee" .= ordinaryTerm callee]
referenceExpectations _ _ _ = []

implicitExpectations :: Text -> [(Expr, Text)] -> [Value]
implicitExpectations rule sources
  | rule == "definition:=", first : _ <- operands = [implicit 0 "defined-value-type" (sourceType first)]
  | rule == "set:in"
  , [_, subset] <- operands =
      let domain = "((fun {α : Type _} (_ : Set α) => α) (" <> subset <> "))"
          container = "Set (" <> domain <> ")"
       in [implicit 0 "element-type" domain, implicit 1 "container-type" container, implicit 2 "membership-instance" ("(inferInstance : Membership " <> domain <> " (" <> container <> "))")]
  | rule == "set:product" =
      [implicit index (if index == 0 then "left-domain" else "right-domain") ("((fun {α : Type _} (_ : Set α) => α) (" <> value <> "))") | (index, value) <- zip [0 ..] operands]
  | rule `elem` ["set:IncludedIn", "set:cap", "set:cup", "macro:SetDifference", "set:=", "set:≠"]
  , first : _ <- operands =
      let domain = sourceType first
          cls = lookup rule [("set:IncludedIn", "LE"), ("set:cap", "Inter"), ("set:cup", "Union"), ("macro:SetDifference", "SDiff")]
       in [implicit 0 "set-type" domain] <> maybe [] (\name -> [implicit 1 "set-operation-instance" ("(inferInstance : " <> name <> " " <> domain <> ")")]) cls
  | rule `elem` ["infix:=", "infix:≠", "infix:<", "infix:≤", "infix:>", "infix:≥"]
  , Just (_, source) <- find (hasSourceVariable . fst) sources =
      let domain = sourceType source
          order = lookup rule [("infix:<", "LT"), ("infix:>", "LT"), ("infix:≤", "LE"), ("infix:≥", "LE")]
       in [implicit 0 "source-operand-type" domain]
            <> maybe [] (\cls -> [implicit 1 "source-order-instance" ("(inferInstance : " <> cls <> " " <> domain <> ")")]) order
  | Just cls <- lookup rule [("macro:frac", "HDiv"), ("infix:+", "HAdd"), ("infix:-", "HSub"), ("infix:*", "HMul"), ("infix:/", "HDiv")]
  , Just (_, source) <- find (hasSourceVariable . fst) sources =
      let domain = sourceType source
       in [implicit i role domain | (i, role) <- zip [0 ..] ["left-type", "right-type", "result-type"]]
            <> [implicit 3 "arithmetic-instance" ("(inferInstance : " <> cls <> " " <> domain <> " " <> domain <> " " <> domain <> ")")]
  | rule `elem` ["macro:ClosedInterval", "macro:OpenInterval", "macro:LeftClosedInterval", "set:real-upper-ray"] =
      [implicit 0 "interval-type" "Real", implicit 1 "interval-order" "(inferInstance : Preorder Real)"]
  | rule == "macro:Ball"
  , center : _ <- operands =
      let domain = sourceType center
       in [implicit 0 "ball-domain" domain, implicit 1 "ball-metric" ("(inferInstance : PseudoMetricSpace " <> domain <> ")")]
  | rule == "macro:Closure"
  , [subset] <- operands =
      let domain = "((fun {α : Type _} (_ : Set α) => α) (" <> subset <> "))"
       in [implicit 0 "closure-domain" domain, implicit 1 "closure-topology" ("(inferInstance : TopologicalSpace " <> domain <> ")")]
  | rule == "macro:Abs"
  , [operand] <- operands
  , any (hasSourceVariable . fst) sources =
      let domain = sourceType operand
       in [ implicit 0 "absolute-value-type" domain
          , implicit 1 "absolute-value-lattice" ("(inferInstance : Lattice " <> domain <> ")")
          , implicit 2 "absolute-value-group" ("(inferInstance : AddGroup " <> domain <> ")")
          ]
  | otherwise = []
 where
  operands = map snd sources
  sourceType value = "(bookSourceType% (" <> value <> "))"
  implicit :: Int -> Text -> Text -> Value
  implicit position role term = object ["argumentPosition" .= position, "role" .= role, "candidate" .= term]

-- The domain witness comes from source references in the AST, not from finding
-- quotation marks or other syntax in the generated Lean program.
