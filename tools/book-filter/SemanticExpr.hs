-- Both forms and their expectations are generated by one traversal. Expectations
-- use ordinary child expressions, never parsing or splitting generated Lean text.
data Rendered = Rendered
  { ordinaryTerm :: Text
  , instrumentedTerm :: Text
  , operatorTraces :: [Value]
  }
  deriving (Eq, Show)

expressionContexts :: Expr -> [Text]
expressionContexts = Set.toList . contexts
 where
  contexts (Reference _ identity) = case bindingConstant identity of
    Just _ -> Set.empty
    Nothing -> maybe Set.empty Set.singleton (bindingContext identity)
  contexts (Macro _ op) = Set.unions (map contexts (toList op))
  contexts (Scoped _ body) = contexts body
  contexts (Parenthesized _ body) = contexts body
  contexts (Scalar _ _ _ left right) = contexts left <> contexts right
  contexts (Compare _ _ _ left right) = contexts left <> contexts right
  contexts (Derived _ body) = contexts body
  contexts (Comparisons values) = Set.unions (map contexts values)
  contexts (Negate _ _ body) = contexts body
  contexts (Index _ _ _ function argument) = contexts function <> contexts argument
  contexts (ShiftIndex _ _ body) = contexts body
  contexts (NamedReference location _ _ identity) = contexts (Reference location identity)
  contexts (Application _ _ _ function arguments) = contexts function <> Set.unions (map contexts arguments)
  contexts (MetricApplication _ _ _ _ _ metric left right) = contexts metric <> contexts left <> contexts right
  contexts (SubtypeRange _ _ _ function predicate) = contexts function <> contexts predicate
  contexts (SubtypeApplication _ _ _ function argument) = contexts function <> contexts argument
  contexts (UniversalSet _ carrier) = contexts carrier
  contexts (SetExpression _ _ _ left right) = contexts left <> contexts right
  contexts (EmbeddedRationalComplement _ _ left right) = contexts left <> contexts right
  contexts (Lambda _ _ binder body) = contexts body <> maybe Set.empty Set.singleton (binderContext binder)
  contexts (DefiningEquality _ _ left right) = contexts left <> contexts right
  contexts (EmptySet _ ambient) = contexts ambient
  contexts (UpperRay _ _ _ endpoint _) = contexts endpoint
  contexts (IntegerCast _ body) = contexts body
  contexts (IntegerNegate _ _ body) = contexts body
  contexts (RealIntegerPower _ _ base powerIndex) = contexts base <> contexts powerIndex
  contexts (RealSequenceSpace _ _ _ powerIndex) = contexts powerIndex
  contexts (FunctionType _ _ _ domain codomain) = contexts domain <> contexts codomain
  contexts (TypeDeclaration _ _ ty function) = contexts ty <> contexts function
  contexts (HomeomorphismType _ _ left right) = contexts left <> contexts right
  contexts (NonemptyType _ _ ty) = contexts ty
  contexts (FiniteIndex _ dimension) = contexts dimension
  contexts (CoordinateSpace _ _ _ alphabet index) = contexts alphabet <> contexts index
  contexts (SubtypeType _ _ _ predicate) = contexts predicate
  contexts (TypedMapForall _ _ identity domain body) = contexts domain <> contexts body <> maybe Set.empty Set.singleton (bindingBinderContext identity)
  contexts (MultipleCalls body) = contexts body
  contexts (FamilyLambda _ _ _ body) = contexts body
  contexts (DependentSum _ _ family) = contexts family
  contexts (IndexedSet _ _ _ _ family) = contexts family
  contexts (RepeatedTuple _ _ witness points) = contexts witness <> Set.unions (map contexts points)
  contexts (Literal _ _ (SequenceLiteral (SequenceWitness _ body)) _) = contexts body
  contexts (ConvergenceSequence _ (SequenceWitness _ body) limit) = contexts body <> contexts limit
  contexts (SequenceConvergence _ _ _ _ sequence' limit) = contexts sequence' <> contexts limit
  contexts (SumFunction _ _ bound body) = maybe Set.empty contexts bound <> contexts body
  contexts (Summation _ _ _ _ bound function) = maybe Set.empty contexts bound <> contexts function
  contexts (ImplicitMultiply _ _ left right) = contexts left <> contexts right
  contexts (RealScalar _ body) = contexts body
  contexts (AmbientSetClosure _ carrier subset) = contexts carrier <> contexts subset
  contexts (ExplicitMetricBall _ _ _ metric center radius) = contexts metric <> contexts center <> contexts radius
  contexts (ExplicitMetricDiameter _ _ metric subset) = contexts metric <> contexts subset
  contexts (DistanceFunction _ _ function) = contexts function
  contexts (Restriction _ function subset) = contexts function <> contexts subset
  contexts (Composition _ _ outer inner) = contexts outer <> contexts inner
  contexts (PointwiseComparison _ _ _ witness left right) = contexts witness <> contexts left <> contexts right
  contexts (BoundFunction _ _ _ body) = contexts body
  contexts (SetComprehension _ _ _ identity domain function) = maybe Set.empty Set.singleton (bindingBinderContext identity) <> maybe Set.empty contexts domain <> contexts function
  contexts (ImageSet _ _ _ function domain) = contexts function <> contexts domain
  contexts (Infimum _ _ image) = contexts image
  contexts (RepeatedEvaluation body) = contexts body
  contexts (CaseBranch _ _ _ _ condition body) = contexts condition <> contexts body
  contexts (DependentConditional _ _ _ condition first second) = contexts condition <> contexts first <> contexts second
  contexts (SigmaPair _ _ tag point) = contexts tag <> contexts point
  contexts (Literal _ _ (WitnessLiteral domain) _) = maybe Set.empty (const (Set.singleton (numericContext domain))) (numericWitness domain)
  contexts (OperatorSection _ _ _ _ _ bound) = contexts bound
  contexts (Conjunction _ _ left right) = contexts left <> contexts right
  contexts (SingletonSet _ _ _ _ point) = contexts point
  contexts (PropositionPair left right) = contexts left <> contexts right
  contexts (MembershipEquality _ _ left middle domain) = contexts left <> contexts middle <> contexts domain
  contexts (InclusionMap _ _ left right) = contexts left <> contexts right
  contexts (RangeFamily _ _ identity range) = maybe Set.empty Set.singleton (bindingContext identity) <> rangeContexts range
  contexts (DecreasingFamily _ _ _ _ _ family) = contexts family
  contexts (RepeatedBinary _ _ _ _ _ _ family) = contexts family
  contexts (TypedRange _ _ function) = contexts function
  contexts (Coerce _ _ point) = contexts point
  contexts (TypedLambda _ _ _ _ _ body) = contexts body
  contexts (Aggregate _ _ _ family) = contexts family
  contexts (SetIdentity _ _ left right) = contexts left <> contexts right
  contexts (MetricBoundedSet _ metric subset) = contexts metric <> contexts subset
  contexts (ExistentialSetPredicate _ _ carrier binders value condition) = Set.unions (map contexts (carrier : value : condition : map snd binders))
  contexts (GuardedSet _ _ _ carrier _ predicate) = contexts carrier <> contexts predicate
  contexts (GeneratedUnion _ _ carrier _ family) = contexts carrier <> contexts family
  contexts _ = Set.empty
  rangeContexts (NaturalTail _ _) = Set.empty
  rangeContexts (FiniteNaturalInterval _ _ upper) = contexts upper

renderedValue :: Rendered -> Value
renderedValue result =
  object
    ["ordinary" .= ordinaryTerm result, "instrumented" .= instrumentedTerm result, "mappings" .= operatorTraces result]

renderCarrier :: (Expr -> Text) -> FamilyCarrier -> Text
renderCarrier plain carrier = case carrier of
  DirectCarrier carrierValue -> plain carrierValue
  IndexedPredicateCarrier family -> "((fun {α : Type _} (_ : Nat → Set α) => α) (" <> plain family <> "))"

sequenceCodomain :: (Expr -> Text) -> SequenceWitness -> Text
sequenceCodomain plain (SequenceWitness identity body) =
  "(bookSequenceCodomain% (fun «" <> bindingName identity <> "» : Nat => " <> plain body <> "))"

numericLowering :: Text -> NumericDomain -> Value
numericLowering kind domain = object $ ["kind" .= kind, "type" .= numericType domain, "target" .= numericTarget domain] <> maybe [] (\identity -> ["binding" .= identity]) (numericBinding domain)

renderPair :: [Text] -> Int -> Candidate Expr -> Rendered
renderPair occupied initial (Candidate expression) = snd (walk initial expression)
 where
  -- Ordinary-only witnesses share the same name environment as the term they
  -- justify. Dropping it could capture source references under a fresh binder.
  ordinaryWitness expression' = ordinaryTerm (snd (walk initial expression'))
  metricCarrierTerm carrier metric = case carrier of SourceMetricCarrier domain -> domain; AppliedMetricCarrier -> "(bookMetricDomain% (" <> metric <> "))"
  distanceDomain expression' = case expression' of
    DistanceFunction _ (MetricDistance carrier) metric -> Just (metricCarrierTerm carrier (ordinaryWitness metric))
    DistanceFunction _ (BinaryDistance domain) _ -> Just domain
    _ -> Nothing
  walk next (ExplicitLean term) = (next, Rendered term term [])
  walk next (Reference _ identity) =
    let name = fromMaybe ("«" <> bindingName identity <> "»") (bindingConstant identity)
        term = case bindingAdaptation identity of
          DirectReference -> name
          SubtypeValue -> "(Subtype.val " <> name <> ")"
          NaturalOffset offset -> "((" <> name <> " : Nat) + " <> T.pack (show offset) <> ")"
     in (next, Rendered term term [])
  walk next (Literal _ _ InferredLiteral term) = (next, Rendered term term [])
  walk next (SourceConstant _ term) = (next, Rendered term term [])
  walk next (MultipleCalls body) =
    let (after, value) = walk next body
        traces = case reverse (operatorTraces value) of
          Object fields : rest -> reverse (Object (KM.insert "allowMultipleCalls" (Bool True) fields) : rest)
          _ -> operatorTraces value
     in (after, value{operatorTraces = traces})
  walk next (RepeatedEvaluation body) =
    let (after, value) = walk next body
        repeated (Object fields) = Object (KM.insert "allowMultipleCalls" (Bool True) fields)
        repeated other = other
     in (after, value{operatorTraces = map repeated (operatorTraces value)})
  walk next (CaseBranch location separator name resultType condition body) =
    let (afterCondition, predicate) = walk next (RepeatedEvaluation condition)
        (afterBody, value) = walk afterCondition body
        term project = "(fun «" <> name <> "» : (" <> project predicate <> ") => (" <> project value <> " : " <> resultType <> "))"
        expected = [object ["sourceOperand" .= (0 :: Int), "target" .= ("lambda.body" :: Text), "candidate" .= ordinaryTerm value], object ["sourceOperand" .= (Nothing :: Maybe Int), "target" .= ("lambda.domain" :: Text), "candidate" .= ordinaryTerm predicate]]
     in recordWith ["expectedBinderName" .= name, "expectedOperands" .= expected] afterBody location (SourceSpan (spanStart separator) (spanStart separator + 1)) "binder:case" [body] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces predicate <> operatorTraces value)
  walk next (DependentConditional location operator rule condition first second) =
    let (afterCondition, predicate) = walk next (RepeatedEvaluation condition)
        (afterFirst, whenTrue) = walk afterCondition first
        (afterSecond, whenFalse) = walk afterFirst second
        term project = "(@dite " <> conditionalResult rule <> " (" <> project predicate <> ") (Classical.propDecidable _) (" <> project whenTrue <> ") (" <> project whenFalse <> "))"
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("result-type" :: Text), "candidate" .= conditionalResult rule], object ["argumentPosition" .= (2 :: Int), "role" .= ("condition-decision" :: Text), "candidate" .= ("Classical.propDecidable (" <> ordinaryTerm predicate <> ")")]]
     in recordWith ["expectedConstant" .= ("dite" :: Text), "expectedImplicitArguments" .= implicit] afterSecond location operator (conditionalTraceRule rule) [condition, first, second] [predicate, whenTrue, whenFalse] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces predicate <> operatorTraces whenTrue <> operatorTraces whenFalse)
  walk next (SigmaPair location familyName tag point) =
    let (afterTag, index) = walk next tag
        (afterPoint, value) = walk afterTag point
        family = "«" <> familyName <> "»"
        term project = "Sigma.mk (β := " <> family <> ") (" <> project index <> ") (" <> project value <> ")"
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("tag-domain" :: Text), "candidate" .= ("Nat" :: Text)], object ["argumentPosition" .= (1 :: Int), "role" .= ("fiber-family" :: Text), "candidate" .= family]]
     in recordWith ["expectedConstant" .= ("Sigma.mk" :: Text), "expectedImplicitArguments" .= implicit] afterPoint location (SourceSpan (spanStart location) (spanStart location + 5)) "constructor:sigma-pair" [tag, point] [index, value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces index <> operatorTraces value)
  walk next (Literal location operator (WitnessLiteral domain) number) =
    let witness = maybe ("(@" <> numericContext domain <> ")") (\name -> "«" <> name <> "»") (numericWitness domain)
        term = "(bookTypedNumeral% (" <> numericType domain <> "), (" <> witness <> "), " <> number <> ")"
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("numeral-type" :: Text), "candidate" .= numericType domain], object ["argumentPosition" .= (2 :: Int), "role" .= ("numeral-instance" :: Text), "candidate" .= ("(inferInstance : OfNat " <> numericType domain <> " " <> number <> ")")]]
        expected = [object ["sourceOperand" .= (Nothing :: Maybe Int), "target" .= ("numeral-value" :: Text), "candidate" .= ("(" <> number <> " : Nat)")]]
     in recordWith ["expectedConstant" .= ("OfNat.ofNat" :: Text), "lowering" .= numericLowering "witness-result-type" domain, "expectedOperands" .= expected, "expectedImplicitArguments" .= implicit] next location operator "literal:numeral" [] [] term term []
  walk next (OperatorSection location operator rule name domain bound) =
    let (after, value) = walk next bound
        comparison project = "(«" <> name <> "» " <> comparisonSymbol (sectionComparison rule) <> " (" <> project value <> "))"
        expected = [object ["sourceOperand" .= (Nothing :: Maybe Int), "target" .= sectionOperandRole rule, "candidate" .= ("«" <> name <> "»")], object ["sourceOperand" .= (0 :: Int), "candidate" .= ordinaryTerm value]]
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= sectionTypeRole rule, "candidate" .= sectionDomain rule], object ["argumentPosition" .= (1 :: Int), "role" .= sectionOrderRole rule, "candidate" .= ("(inferInstance : " <> sectionOrderClass rule <> " " <> sectionDomain rule <> ")")]]
        (afterComparison, predicate) = recordWith ["expectedConstant" .= sectionHead rule, "expectedOperands" .= expected, "expectedImplicitArguments" .= implicit] after location operator (sectionTraceRule rule) [bound] [value] (comparison ordinaryTerm) (comparison instrumentedTerm) (operatorTraces value)
        term project = "(fun «" <> name <> "» : " <> sectionDomain rule <> " => " <> project predicate <> ")"
        binderExpected = [object ["sourceOperand" .= (0 :: Int), "target" .= ("lambda.body" :: Text), "candidate" .= ordinaryTerm predicate], object ["sourceOperand" .= (Nothing :: Maybe Int), "target" .= ("lambda.domain" :: Text), "candidate" .= sectionDomain rule]]
     in recordWith ["expectedBinderName" .= name, "expectedBinderTypeName" .= sectionDomain rule, "expectedConstant" .= Null, "lowering" .= numericLowering (sectionLowering rule) domain, "expectedOperands" .= binderExpected] afterComparison location operator (sectionBinderRule rule) [Scoped location bound] [predicate] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces predicate)
  walk next (ContextualLiteral location operator identity constant consumer literal) =
    let LiteralConsumer declaration callee position = consumer
        extra = ["interpretationId" .= identity, "expectedConstant" .= constant, "consumer" .= object ["declaration" .= declaration, "callee" .= callee, "argumentPosition" .= position], "lowering" .= object ["kind" .= ("contextual-literal" :: Text), "sourceLiteral" .= literal]]
     in recordWith extra next location operator "literal:contextual-constant" [] [] constant constant []
  walk next (Literal location _ (SequenceLiteral witness) number) =
    let domain = sequenceCodomain ordinaryWitness witness
        term = "(" <> number <> " : " <> domain <> ")"
        expected = [object ["sourceOperand" .= (0 :: Int), "candidate" .= ("(" <> number <> " : Nat)")]]
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("sequence-codomain" :: Text), "candidate" .= domain], object ["argumentPosition" .= (2 :: Int), "role" .= ("limit-numeral-instance" :: Text), "candidate" .= ("(inferInstance : OfNat (" <> domain <> ") " <> number <> ")")]]
        extra = ["expectedConstant" .= ("OfNat.ofNat" :: Text), "lowering" .= object ["kind" .= ("sequence-codomain-numeral" :: Text)], "expectedOperands" .= expected, "expectedImplicitArguments" .= implicit]
     in recordWith extra next location location "literal:sequence-limit" [Literal location location InferredLiteral number] [Rendered number number []] term term []
  walk next (SumFunction _ identity bound body) =
    let (afterBound, lower) = case bound of Nothing -> (next, Nothing); Just expression' -> let (after, boundValue) = walk next expression' in (after, Just boundValue)
        (afterBody, value) = walk afterBound body
        name = bindingName identity
        term project = case lower of
          Nothing -> "(fun «" <> name <> "» : ℕ => (" <> project value <> " : ℝ))"
          Just start -> let offset = name <> "_tail_offset" in "(fun «" <> offset <> "» : ℕ => let «" <> name <> "» : ℕ := «" <> offset <> "» + (" <> project start <> " : ℕ); (" <> project value <> " : ℝ))"
     in (afterBody, Rendered (term ordinaryTerm) (term instrumentedTerm) (maybe [] operatorTraces lower <> operatorTraces value))
  walk next (Summation location operator components kind bound function) =
    let finite = kind == FiniteSum
        (afterBound, range) = if finite then case bound of Just expression' -> let (after, value) = walk next expression' in (after, Just value); Nothing -> (next, Nothing) else (next, fmap (\expression' -> let sourceTerm = ordinaryWitness expression' in Rendered sourceTerm sourceTerm []) bound)
        (afterFunction, family) = walk afterBound function
        operands = maybe [function] (\source -> [source, function]) bound
        children = maybe [family] (\source -> [source, family]) range
        term project = if finite then "Finset.sum (Finset.range (" <> maybe "" project range <> " : ℕ)) (" <> project family <> ")" else "tsum (" <> project family <> ")"
        expected = if finite then [object ["sourceOperand" .= (0 :: Int), "candidate" .= ("Finset.range (" <> maybe "" ordinaryTerm range <> " : ℕ)")], object ["sourceOperand" .= (1 :: Int), "candidate" .= ordinaryTerm family]] else [object ["sourceOperand" .= (length operands - 1), "candidate" .= ordinaryTerm family], object ["sourceOperand" .= (Nothing :: Maybe Int), "candidate" .= ("SummationFilter.unconditional ℕ" :: Text)]]
        parameters = if finite then ["ℕ", "ℝ", "(inferInstance : AddCommMonoid ℝ)"] else ["ℝ", "ℕ", "(inferInstance : AddCommMonoid ℝ)", "(inferInstance : TopologicalSpace ℝ)"] :: [Text]
        implicit = [object ["argumentPosition" .= index, "role" .= ("summation-parameter" :: Text), "candidate" .= parameter] | (index, parameter) <- zip [0 :: Int ..] parameters]
        rule = case kind of FiniteSum -> "sum:finite"; InfiniteSum -> "sum:infinite"; TailSum -> "sum:tail"
        extra = ["expectedOperands" .= expected, "expectedImplicitArguments" .= implicit, "bindingComponents" .= [object ["start" .= spanStart source, "end" .= spanEnd source, "target" .= role] | (source, role) <- components]]
     in recordWith extra afterFunction location operator rule operands children (term ordinaryTerm) (term instrumentedTerm) (maybe [] operatorTraces range <> operatorTraces family)
  walk next (ImplicitMultiply location operator left right) =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        term project = "(" <> project lhs <> " * " <> project rhs <> ")"
        implicit = [object ["argumentPosition" .= index, "role" .= ("multiplication-type" :: Text), "candidate" .= ("ℝ" :: Text)] | index <- [0 :: Int .. 2]] <> [object ["argumentPosition" .= (3 :: Int), "role" .= ("multiplication-instance" :: Text), "candidate" .= ("(inferInstance : HMul ℝ ℝ ℝ)" :: Text)]]
     in recordWith ["lowering" .= ("juxtaposition" :: Text), "expectedImplicitArguments" .= implicit] afterRight location operator "infix:implicit-multiply" [left, right] [lhs, rhs] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs)
  walk next (RealScalar _ body) =
    let (after, value) = walk next body
        term project = "((" <> project value <> ") : ℝ)"
     in (after, Rendered (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value))
  walk next (AmbientSetClosure location carrier subset) =
    let (afterCarrier, ambient) = walk next carrier
        (afterSet, value) = walk afterCarrier subset
        term project = "(@closure (" <> project ambient <> ") inferInstance (" <> project value <> "))"
        implicit = [object ["argumentPosition" .= (0 :: Int), "sourceOperand" .= (0 :: Int), "role" .= ("closure-domain" :: Text), "candidate" .= ordinaryTerm ambient], object ["argumentPosition" .= (1 :: Int), "role" .= ("closure-topology" :: Text), "candidate" .= ("(inferInstance : TopologicalSpace (" <> ordinaryTerm ambient <> "))")]]
     in recordWith ["expectedImplicitArguments" .= implicit] afterSet location (SourceSpan (spanStart location) (spanStart location + 15)) "macro:AmbientClosure" [carrier, subset] [ambient, value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces ambient <> operatorTraces value)
  walk next (ExplicitMetricBall location carrier proof metric center radius) =
    let (afterMetric, metricValue) = walk next metric
        (afterCenter, point) = walk afterMetric center
        (afterRadius, size) = walk afterCenter radius
        sourceMetric = ordinaryTerm metricValue
        domain = "(bookMetricDomain% (" <> sourceMetric <> "))"
        adapt value = case proof of Nothing -> "(bookMetricPoint% (" <> domain <> "), (" <> value <> "))"; Just name -> "(bookEqualMetricPoint% (" <> domain <> "), (" <> value <> "), «" <> name <> "»)"
        term project = "(@Metric.ball (" <> metricCarrierTerm carrier sourceMetric <> ") (" <> project metricValue <> ").toPseudoMetricSpace (" <> adapt (project point) <> ") (" <> project size <> " : ℝ))"
        expected = [object ["sourceOperand" .= (1 :: Int), "candidate" .= adapt (ordinaryTerm point)], object ["sourceOperand" .= (2 :: Int), "candidate" .= ordinaryTerm size]]
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("ball-domain" :: Text), "candidate" .= domain], object ["argumentPosition" .= (1 :: Int), "sourceOperand" .= (0 :: Int), "role" .= ("ball-metric" :: Text), "candidate" .= ("(" <> sourceMetric <> ").toPseudoMetricSpace")]]
     in recordWith ["lowering" .= object ["kind" .= ("explicit-metric-ball" :: Text)], "expectedOperands" .= expected, "expectedImplicitArguments" .= implicit] afterRadius location (SourceSpan (spanStart location) (spanStart location + 11)) "macro:MetricBall" [metric, center, radius] [metricValue, point, size] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces metricValue <> operatorTraces point <> operatorTraces size)
  walk next (ExplicitMetricDiameter location carrier metric subset) =
    let (afterMetric, metricValue) = walk next metric
        (afterSet, value) = walk afterMetric subset
        sourceMetric = ordinaryTerm metricValue
        adapt setValue = "(bookMetricSet% (" <> sourceMetric <> "), (" <> setValue <> "))"
