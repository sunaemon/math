          Nothing -> (after, Rendered plain traced previous)
          Just span' ->
            record
              after
              span'
              (SourceSpan (spanStart span') (spanStart span' + T.length name + 1))
              ("macro:" <> name)
              (toList op)
              (toList children)
              plain
              traced
              previous
  walk next (Scalar location operator op left right) =
    binary next location operator ("infix:" <> arithmeticSymbol op) (arithmeticSymbol op) left right
  walk next (Compare location operator op left right) =
    binary next location operator ("infix:" <> comparisonSymbol op) (comparisonSymbol op) left right
  walk next (SetIdentity location operator left right) =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        term project = "(" <> project lhs <> " = " <> project rhs <> ")"
     in recordWith ["expectedConstant" .= ("Eq" :: Text)] afterRight location operator "set:=" [left, right] [lhs, rhs] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs)
  walk next (MetricBoundedSet _ metric subset) =
    let witness = ordinaryWitness metric
        lifted = "(bookMetricSet% (" <> witness <> "), (" <> ordinaryWitness subset <> "))"
        term = "@Bornology.IsBounded (bookMetricDomain% (" <> witness <> ")) (" <> witness <> ").toPseudoMetricSpace.toBornology (" <> lifted <> ")"
     in (next, Rendered term term [])
  walk next (ExistentialSetPredicate _ name carrier binders body condition) =
    let (afterBinders, domains) = mapAccumL (\index (_, domain) -> walk index domain) next binders
        (afterBody, value) = walk afterBinders body
        (afterCondition, predicate) = walk afterBody condition
        term project = "(fun «" <> name <> "» : Set (" <> ordinaryWitness carrier <> ") => " <> T.concat ["∃ «" <> binder <> "» : " <> project domain <> ", " | ((binder, _), domain) <- zip binders domains] <> "«" <> name <> "» = (" <> project value <> ") ∧ (" <> project predicate <> "))"
     in (afterCondition, Rendered (term ordinaryTerm) (term instrumentedTerm) (concatMap operatorTraces domains <> operatorTraces value <> operatorTraces predicate))
  walk next (GuardedSet location operator components carrier evidence predicate) =
    let (after, value) = walk next predicate
        term project = "Set.ofPred (" <> project value <> ")"
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("set-domain" :: Text), "candidate" .= ("Set (" <> ordinaryWitness carrier <> ")")]]
        sourceComponents = [object ["start" .= spanStart source, "end" .= spanEnd source, "target" .= role] | (source, role) <- components]
     in recordWith ["bindingComponents" .= sourceComponents, "sourceRestriction" .= restrictionValue evidence, "expectedImplicitArguments" .= implicit] after location operator "binder:predicate-set" [predicate] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (GeneratedUnion location operator carrier evidence family) =
    let (after, value) = walk next family
        term project = "Set.sUnion (" <> project value <> ")"
        implicit = [object ["argumentPosition" .= (0 :: Int), "role" .= ("union-domain" :: Text), "candidate" .= ordinaryWitness carrier]]
     in recordWith ["expectedConstant" .= ("Set.sUnion" :: Text), "sourceRestriction" .= restrictionValue evidence, "expectedImplicitArguments" .= implicit] after location operator "set:generated-union" [family] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (PropositionPair left right) =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        term project = "((" <> project lhs <> ") ∧ (" <> project rhs <> "))"
     in (afterRight, Rendered (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs))
  walk next (MembershipEquality location operator left middle domain) =
    let (afterLeft, lhs) = walk next left
        (afterMiddle, rhs) = walk afterLeft middle
        subset = ordinaryWitness domain
        point value = "(bookSetPoint% (" <> subset <> "), (" <> value <> "))"
        convert value = value{ordinaryTerm = point (ordinaryTerm value), instrumentedTerm = point (instrumentedTerm value)}
        converted = [convert lhs, convert rhs]
        term project = "((" <> project (convert lhs) <> ") = (" <> project (convert rhs) <> "))"
        expected = [object ["sourceOperand" .= index, "candidate" .= ordinaryTerm value] | (index, value) <- zip [0 :: Int ..] converted]
        implicit = [object ["argumentPosition" .= (0 :: Int), "sourceOperand" .= (2 :: Int), "role" .= ("membership-ambient-type" :: Text), "candidate" .= ("((fun {α : Type _} (_ : Set α) => α) (" <> subset <> "))")]]
        lowering = object ["kind" .= ("equality-membership-chain" :: Text), "pointAdapter" .= ("identity-or-Subtype.val" :: Text)]
     in recordWith ["expectedConstant" .= ("Eq" :: Text), "expectedOperands" .= expected, "expectedImplicitArguments" .= implicit, "lowering" .= lowering] afterMiddle location operator "relation:membership-chain-equality" [left, middle, domain] converted (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs)
  walk next (InclusionMap location operator left right) =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        proof project = "(show (" <> project lhs <> ") ⊆ (" <> project rhs <> ") from by intro z hz; aesop (config := { maxRuleApplications := 100 }))"
        term project = "Set.inclusion (" <> proof project <> ")"
        expected = [object ["sourceOperand" .= (Nothing :: Maybe Int), "candidate" .= proof ordinaryTerm]]
        implicit =
          [ object ["argumentPosition" .= (0 :: Int), "role" .= ("inclusion-ambient-type" :: Text), "candidate" .= ("((fun {α : Type _} (_ : Set α) => α) (" <> ordinaryTerm lhs <> "))")]
          , object ["argumentPosition" .= (1 :: Int), "sourceOperand" .= (0 :: Int), "role" .= ("inclusion-source" :: Text), "candidate" .= ordinaryTerm lhs]
          , object ["argumentPosition" .= (2 :: Int), "sourceOperand" .= (1 :: Int), "role" .= ("inclusion-target" :: Text), "candidate" .= ordinaryTerm rhs]
          ]
     in recordWith ["expectedConstant" .= ("Set.inclusion" :: Text), "expectedOperands" .= expected, "expectedImplicitArguments" .= implicit] afterRight location operator "map:inclusion" [left, right] [lhs, rhs] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs)
  walk next (RangeFamily _ name identity range) =
    let family = fromMaybe ("«" <> bindingName identity <> "»") (bindingConstant identity)
        (domain, projection, lower, origin) = case range of
          NaturalTail first sourceOrigin -> ("Nat", "", first, sourceOrigin)
          FiniteNaturalInterval first sourceOrigin upper -> ("Fin ((" <> ordinaryWitness upper <> ") - " <> T.pack (show first) <> " + 1)", ".val", first, sourceOrigin)
        term = "(fun «" <> name <> "» : " <> domain <> " => (" <> family <> ") («" <> name <> "»" <> projection <> " + " <> T.pack (show lower) <> " - " <> T.pack (show origin) <> "))"
     in (next, Rendered term term [])
  walk next (DecreasingFamily location operator components first origin family) =
    let (after, value) = walk next family
        codomain = "((fun {α β : Type _} (_ : α → β) => β) (" <> ordinaryTerm value <> "))"
        implicit position role expected = object ["argumentPosition" .= (position :: Int), "role" .= (role :: Text), "candidate" .= (expected :: Text)]
        lowering = object ["kind" .= ("decreasing-natural-tail" :: Text), "firstIndex" .= first, "sourceOrigin" .= origin]
        expectations = [implicit 0 "index-type" "Nat", implicit 1 "set-type" codomain, implicit 2 "index-order" "(inferInstance : Preorder Nat)", implicit 3 "set-order" ("(inferInstance : Preorder " <> codomain <> ")")]
        sourceComponents = [object ["start" .= spanStart source, "end" .= spanEnd source, "role" .= role] | (source, role) <- components]
        term project = "Antitone (" <> project value <> ")"
     in recordWith ["expectedConstant" .= ("Antitone" :: Text), "lowering" .= lowering, "bindingComponents" .= sourceComponents, "expectedImplicitArguments" .= expectations] after location operator "relation:decreasing-family" [family] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (RepeatedBinary location operator components identity range (FoldPlan _ _ headName rule lattice) family) =
    let (after, value) = walk next family
        codomain = "((fun {α β : Type _} (_ : α → β) => β) (" <> ordinaryTerm value <> "))"
        implicit position role expected = object ["argumentPosition" .= (position :: Int), "role" .= (role :: Text), "candidate" .= (expected :: Text)]
        (domain, lowering) = case range of
          NaturalTail first origin -> ("Nat", object ["kind" .= ("natural-tail" :: Text), "firstIndex" .= first, "sourceOrigin" .= origin])
          FiniteNaturalInterval first origin upper -> ("Fin ((" <> ordinaryWitness upper <> ") - " <> T.pack (show first) <> " + 1)", object ["kind" .= ("finite-natural-interval" :: Text), "firstIndex" .= first, "lastIndex" .= ordinaryWitness upper, "sourceOrigin" .= origin, "family" .= bindingName identity])
        expectations = [implicit 0 "set-type" codomain, implicit 1 "index-type" domain, implicit 2 "set-lattice" ("(inferInstance : " <> lattice <> " " <> codomain <> ")")]
        sourceComponents = [object ["start" .= spanStart source, "end" .= spanEnd source, "role" .= role] | (source, role) <- components]
        term project = headName <> " (" <> project value <> ")"
     in recordWith ["expectedConstant" .= headName, "lowering" .= lowering, "bindingComponents" .= sourceComponents, "expectedImplicitArguments" .= expectations] after location operator rule [family] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (Conjunction location operator left right) =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        term project = "And (" <> project lhs <> ") (" <> project rhs <> ")"
     in recordWith ["expectedConstant" .= ("And" :: Text)] afterRight location operator "logic:and" [left, right] [lhs, rhs] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs)
  walk next (Derived origin body) =
    let (after, result) = walk next body
     in (after, result{operatorTraces = annotateRoot origin (operatorTraces result)})
  walk next (SingletonSet location operator closing annotation point) =
    singleton next location operator closing annotation point
  walk next (CoercionFunction _ rule) =
    let term = "((↑) : " <> coercionSourceDisplay rule <> " → " <> coercionTargetDisplay rule <> ")"
     in (next, Rendered term term [])
  walk next (TypedRange location rule function) =
    let (after, value) = walk next function
        term project = "(Set.range (" <> project value <> ") : Set " <> coercionTargetDisplay rule <> ")"
        implicit = [object ["argumentPosition" .= position, "role" .= ("ambient-parameter" :: Text), "candidate" .= (ty :: Text)] | (position, ty) <- zip [0 :: Int ..] [coercionTarget rule, coercionSource rule]]
     in recordWith ["expectedConstant" .= ("Set.range" :: Text), "expectedImplicitArguments" .= implicit] after location location (coercionRangeRule rule) [function] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (Coerce location rule point) =
    let (after, value) = walk next point
        term project = "(" <> coercionHead rule <> " (" <> project value <> ") : " <> coercionTargetDisplay rule <> ")"
        implicit = [object ["argumentPosition" .= position, "role" .= ("ambient-parameter" :: Text), "candidate" .= (ty :: Text)] | (position, ty) <- zip [0 :: Int ..] [coercionTarget rule, "(inferInstance : " <> coercionClass rule <> " " <> coercionTarget rule <> ")"]]
     in recordWith ["expectedConstant" .= coercionHead rule, "expectedImplicitArguments" .= implicit] after location location (coercionTraceRule rule) [point] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (TypedLambda location rule identity syntax subscript body) =
    let (after, value) = walk next body
        term project = "(fun «" <> bindingName identity <> "» : " <> lambdaDomain rule <> " => (" <> project value <> " : " <> lambdaResult rule <> "))"
        sourceComponent node = case locatedValue node of Object fields -> Object (KM.insert "target" (String "lambda.domain") fields); other -> other
        components = map sourceComponent syntax <> [object ["start" .= spanStart subscript, "end" .= spanEnd subscript, "target" .= ("lambda.domain" :: Text)]]
        expected = [object ["sourceOperand" .= (0 :: Int), "target" .= ("lambda.body" :: Text), "candidate" .= ordinaryTerm value], object ["sourceOperand" .= (Nothing :: Maybe Int), "target" .= ("lambda.domain" :: Text), "candidate" .= lambdaDomain rule]]
     in recordWith ["expectedBinderName" .= bindingName identity, "expectedBinderTypeName" .= lambdaDomain rule, "bindingComponents" .= components, "expectedOperands" .= expected] after location location "binder:mapsto" [body] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (Aggregate location rule (AmbientEvidence ty scope source) family) =
    let (after, value) = walk next family
        term project = aggregationHead rule <> " (" <> project value <> ")"
        codomain = "((fun {α β : Type _} (_ : α → β) => β) (" <> ordinaryTerm value <> "))"
        implicit position role expected = object ["argumentPosition" .= (position :: Int), "role" .= (role :: Text), "candidate" .= (expected :: Text)]
        evidence = object ["type" .= ty, "scope" .= scope, "start" .= spanStart source, "end" .= spanEnd source]
     in recordWith ["expectedConstant" .= aggregationHead rule, "sourceAmbient" .= evidence, "expectedImplicitArguments" .= [implicit 0 "set-type" codomain, implicit 1 "index-type" (aggregationIndex rule), implicit 2 "set-lattice" ("(inferInstance : " <> aggregationLattice rule <> " " <> codomain <> ")")]] after location location (aggregationTraceRule rule) [family] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  walk next (DefiningEquality location operator left right) =
    binary next location operator "definition:=" "=" left right
  walk next (EmptySet location ambient) =
    -- The other source set supplies a type witness, not an additional operand
    -- occurrence. Its ordinary expression must not emit another marker.
    let witness = ordinaryWitness ambient
        domain = "((fun {α : Type _} (_ : Set α) => α) (" <> witness <> "))"
        container = "Set (" <> domain <> ")"
        term = "(∅ : Set (" <> domain <> "))"
        expectations = [object ["argumentPosition" .= (0 :: Int), "role" .= ("empty-set-type" :: Text), "candidate" .= container], object ["argumentPosition" .= (1 :: Int), "role" .= ("empty-set-instance" :: Text), "candidate" .= ("(inferInstance : EmptyCollection (" <> container <> "))")]]
     in recordWith ["expectedImplicitArguments" .= expectations] next location (SourceSpan (spanStart location) (spanStart location + 9)) "set:empty" [] [] term term []
  walk next (Comparisons values) =
    let (after, children) = mapAccumL walk next values
        joinTerms project = "(" <> T.intercalate " ∧ " (map project children) <> ")"
     in (after, Rendered (joinTerms ordinaryTerm) (joinTerms instrumentedTerm) (concatMap operatorTraces children))
  walk next (Negate location operator body) =
    let (after, child) = walk next body
        term value = "(-(" <> value <> "))"
     in record after location operator "unary:-" [body] [child] (term (ordinaryTerm child)) (term (instrumentedTerm child)) (operatorTraces child)
  walk next (IntegerNegate location operator body) =
    let (after, child) = walk next body
        term value = "(-(" <> value <> "))"
        expectations = [object ["argumentPosition" .= (0 :: Int), "role" .= ("negation-domain" :: Text), "candidate" .= ("ℤ" :: Text)], object ["argumentPosition" .= (1 :: Int), "role" .= ("negation-instance" :: Text), "candidate" .= ("(inferInstance : Neg ℤ)" :: Text)]]
     in recordWith ["expectedImplicitArguments" .= expectations] after location operator "unary:-" [body] [child] (term (ordinaryTerm child)) (term (instrumentedTerm child)) (operatorTraces child)
  walk next (RealIntegerPower location operator base powerIndex) =
    let (afterBase, lhs) = walk next base
        (afterExponent, rhs) = walk afterBase powerIndex
        term project = "((" <> project lhs <> " : ℝ) ^ (" <> project rhs <> "))"
        converted = lhs{ordinaryTerm = "(" <> ordinaryTerm lhs <> " : ℝ)", instrumentedTerm = "(" <> instrumentedTerm lhs <> " : ℝ)"}
        expectations = [object ["argumentPosition" .= position, "role" .= (role :: Text), "candidate" .= (value :: Text)] | (position, role, value) <- [(0 :: Int, "power-base-type", "ℝ"), (1, "power-exponent-type", "ℤ"), (2, "power-result-type", "ℝ"), (3, "power-instance", "(inferInstance : HPow ℝ ℤ ℝ)")]]
     in recordWith ["expectedImplicitArguments" .= expectations] afterExponent location operator "power:real-integer" [base, powerIndex] [converted, rhs] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces lhs <> operatorTraces rhs)
  walk next (ShiftIndex _ origin body) =
    let (after, child) = walk next body
        shift value = "((" <> value <> ") - " <> T.pack (show origin) <> ")"
     in (after, child{ordinaryTerm = shift (ordinaryTerm child), instrumentedTerm = shift (instrumentedTerm child)})
  walk next (NamedReference location operator decoration identity) =
    let (after, reference) = walk next (Reference location identity)
        rule = case decoration of SubscriptName -> "name:subscript"; StarredName -> "name:star"
        target = if isNothing (bindingConstant identity) then "expectedVariable" .= bindingName identity else "expectedConstant" .= bindingName identity
     in recordWith [target] after location operator rule [] [] (ordinaryTerm reference) (instrumentedTerm reference) []
  walk next (Application location operator identity function arguments) =
    let (afterFunction, callee) = walk next function
        (afterArguments, children) = mapAccumL walk afterFunction arguments
        apply project = "((" <> project callee <> ") " <> T.intercalate " " ["(" <> project child <> ")" | child <- children] <> ")"
        target = if isNothing (bindingConstant identity) then "expectedVariable" .= bindingName identity else "expectedConstant" .= bindingName identity
     in recordWith [target] afterArguments location operator "application:function" arguments children (apply ordinaryTerm) (apply instrumentedTerm) (operatorTraces callee <> concatMap operatorTraces children)
  walk next (MetricApplication location operator carrier evaluation proof metric left right) =
    let (afterMetric, callee) = walk next metric
        (afterPoints, points) = mapAccumL walk afterMetric [left, right]
        domain = case carrier of SourceMetricCarrier name -> name; AppliedMetricCarrier -> "(bookMetricDomain% (" <> ordinaryTerm callee <> "))"
        point value = case proof of Nothing -> "(bookMetricPoint% (" <> domain <> "), (" <> value <> "))"; Just name -> "(bookEqualMetricPoint% (" <> domain <> "), (" <> value <> "), «" <> name <> "»)"
        converted = [if index == (0 :: Int) || evaluation == PointDistance then child{ordinaryTerm = point (ordinaryTerm child), instrumentedTerm = point (instrumentedTerm child)} else child | (index, child) <- zip [0 ..] points]
        (headName, projection, rule) = case evaluation of
          PointDistance -> ("dist", "toDist", "application:metric")
          SetDistance -> ("Metric.infDist", "toPseudoMetricSpace", "application:distance-to-set")
        apply project = "(@" <> headName <> " _ ((" <> project callee <> "))." <> projection <> " " <> T.intercalate " " ["(" <> project child <> ")" | child <- converted] <> ")"
        implicit position role term = object ["argumentPosition" .= (position :: Int), "role" .= (role :: Text), "candidate" .= term]
        expectations = [implicit 0 "metric-domain" domain, implicit 1 "metric-instance" ("(" <> ordinaryTerm callee <> ")." <> projection)]
        lowering = maybe [] (\name -> ["lowering" .= object ["kind" .= ("equality-transport-between-fibers" :: Text), "branchProof" .= name, "operation" .= ("Eq.mp" :: Text)]]) proof
     in recordWith (["expectedImplicitArguments" .= expectations] <> lowering) afterPoints location operator rule [left, right] converted (apply ordinaryTerm) (apply instrumentedTerm) (operatorTraces callee <> concatMap operatorTraces points)
  walk next (SubtypeRange location operator domainSet function predicate) =
    let (afterFunction, callee) = walk next function
        (afterPredicate, carrier) = walk afterFunction predicate
        apply project = "(bookSubtypeRange% (" <> project callee <> "), (" <> project carrier <> "))"
        expectations =
          [ object ["argumentPosition" .= (0 :: Int), "role" .= ("image-codomain" :: Text), "candidate" .= ("((fun {α β : Type _} (_ : α → β) => β) (" <> ordinaryTerm callee <> "))")]
          , object ["argumentPosition" .= (1 :: Int), "sourceOperand" .= (1 :: Int), "role" .= ("image-domain" :: Text), "candidate" .= ("Subtype (" <> ordinaryTerm carrier <> ")")]
          ]
        extra = ["expectedConstant" .= ("Set.range" :: Text), "lowering" .= object ["kind" .= ("image-of-entire-subtype-domain" :: Text), "domainSet" .= domainSet], "expectedImplicitArguments" .= expectations]
     in recordWith extra afterPredicate location operator "application:subtype-range" [function, predicate] [callee, carrier] (apply ordinaryTerm) (apply instrumentedTerm) (operatorTraces callee <> operatorTraces carrier)
  walk next (SubtypeApplication location operator identity function argument) =
    let (afterFunction, callee) = walk next function
        (afterArgument, point) = walk afterFunction argument
        adapted project = "(bookSubtypeArgument% (" <> project callee <> "), (" <> project point <> "))"
        converted = point{ordinaryTerm = adapted ordinaryTerm, instrumentedTerm = adapted instrumentedTerm}
        apply project = "((" <> project callee <> ") " <> project converted <> ")"
        target = if isNothing (bindingConstant identity) then "expectedVariable" .= bindingName identity else "expectedConstant" .= bindingName identity
     in recordWith [target, "lowering" .= object ["kind" .= ("subtype-argument-from-local-membership" :: Text)]] afterArgument location operator "application:subtype-argument" [argument] [converted] (apply ordinaryTerm) (apply instrumentedTerm) (operatorTraces callee <> operatorTraces point)
  walk next (Index location operator notation function argument) =
    let (afterFunction, callee) = walk next function
        (afterArgument, index) = walk afterFunction argument
        rule = case notation of Subscript -> "index:subscript"; Superscript -> "index:superscript"
        apply f x = "((" <> f <> ") (" <> x <> "))"
     in record afterArgument location operator rule [function, argument] [callee, index] (apply (ordinaryTerm callee) (ordinaryTerm index)) (apply (instrumentedTerm callee) (instrumentedTerm index)) (operatorTraces callee <> operatorTraces index)
  walk next (UniversalSet _ carrier) =
    let (after, child) = walk next carrier
        universal value = "(@Set.univ (" <> value <> "))"
        repeatLast values = case reverse values of Object fields : previous -> reverse (Object (KM.insert "allowMultipleCalls" (Bool True) fields) : previous); _ -> values
     in (after, child{ordinaryTerm = universal (ordinaryTerm child), instrumentedTerm = universal (instrumentedTerm child), operatorTraces = if indexedCarrier carrier then repeatLast (operatorTraces child) else operatorTraces child})
  walk next (SetExpression location operator op left right) =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        point value = "(bookSetPoint% (" <> ordinaryTerm rhs <> "), (" <> value <> "))"
        converted = if op == Member then lhs{ordinaryTerm = point (ordinaryTerm lhs), instrumentedTerm = point (instrumentedTerm lhs)} else lhs
        combine a b = if op == Product then "Set.prod (" <> a <> ") (" <> b <> ")" else "((" <> a <> ") " <> setSymbol op <> " (" <> b <> "))"
     in record afterRight location operator (setRule op) [left, right] [converted, rhs] (combine (ordinaryTerm converted) (ordinaryTerm rhs)) (combine (instrumentedTerm converted) (instrumentedTerm rhs)) (operatorTraces lhs <> operatorTraces rhs)
  singleton next location operator closing annotation point =
    let (after, value) = walk next point
        carrier = "(bookSourceType% (" <> ordinaryWitness point <> "))"
        term project = "(Singleton.singleton (" <> project value <> ") : Set " <> fromMaybe carrier annotation <> ")"
        implicit = [object ["argumentPosition" .= position, "role" .= ("ambient-parameter" :: Text), "candidate" .= expected] | (position, expected) <- zip [0 :: Int ..] [carrier, "Set " <> carrier, "(inferInstance : Singleton " <> carrier <> " (Set " <> carrier <> "))"]]
        components = [object ["start" .= spanStart closing, "end" .= spanEnd closing, "kind" .= ("command" :: Text), "name" .= ("}" :: Text), "optional" .= Null, "args" .= ([] :: [Value]), "target" .= ("singleton.close" :: Text)]]
     in recordWith ["expectedConstant" .= ("Singleton.singleton" :: Text), "expectedImplicitArguments" .= implicit, "bindingComponents" .= components] after location operator "set:singleton" [point] [value] (term ordinaryTerm) (term instrumentedTerm) (operatorTraces value)
  binary = binaryWith []
  binaryWith extra next location operator rule symbol left right =
    let (afterLeft, lhs) = walk next left
        (afterRight, rhs) = walk afterLeft right
        combine a b = "((" <> a <> ") " <> symbol <> " (" <> b <> "))"
     in recordWith
          extra
          afterRight
          location
          operator
          rule
          [left, right]
          [lhs, rhs]
          (combine (ordinaryTerm lhs) (ordinaryTerm rhs))
          (combine (instrumentedTerm lhs) (instrumentedTerm rhs))
          (operatorTraces lhs <> operatorTraces rhs)
  record = recordWith []
  -- Extra source-owned fields may replace defaults, e.g. a metric's independent
  -- carrier/instance expectations. Aeson stores each key only once.
  recordWith extra next location operator rule operands children plain traced previous =
    let fresh name = if name `elem` occupied then fresh (name <> "_") else name
        marker = fresh ("md_operator_" <> T.pack (show next))
        expected = map ordinaryTerm children
        mapping =
          object $
            [ "marker" .= marker
            , "start" .= spanStart location
            , "end" .= spanEnd location
            , "operatorStart" .= spanStart operator
            , "operatorEnd" .= spanEnd operator
            , "rule" .= rule
            , "operandSpans" .= map spanValue (mapMaybe expressionSpan operands)
            , "candidate" .= traced
            , "expectedOperands" .= [object ["sourceOperand" .= index, "candidate" .= value] | (index, value) <- explicitOperands rule expected]
            , "expectedImplicitArguments" .= implicitExpectations rule (zip operands expected)
            ]
              <> referenceExpectations rule operands children
              <> extra
     in (next + 1, Rendered plain ("(let " <> marker <> " := " <> traced <> "; " <> marker <> ")") (previous <> [mapping]))

expressionSpan :: Expr -> Maybe SourceSpan
expressionSpan (Macro location _) = location
expressionSpan (Reference location _) = Just location
expressionSpan (Literal location _ _ _) = Just location
expressionSpan (Scoped location _) = Just location
expressionSpan (Parenthesized location _) = Just location
expressionSpan (Scalar location _ _ _ _) = Just location
expressionSpan (Compare location _ _ _ _) = Just location
expressionSpan (Derived _ body) = expressionSpan body
expressionSpan (Comparisons _) = Nothing
expressionSpan (Conjunction location _ _ _) = Just location
expressionSpan (SingletonSet location _ _ _ _) = Just location
expressionSpan (PropositionPair _ _) = Nothing
expressionSpan (MembershipEquality location _ _ _ _) = Just location
expressionSpan (InclusionMap location _ _ _) = Just location
expressionSpan (RangeFamily location _ _ _) = Just location
expressionSpan (DecreasingFamily location _ _ _ _ _) = Just location
expressionSpan (RepeatedBinary location _ _ _ _ _ _) = Just location
expressionSpan (CoercionFunction location _) = Just location
expressionSpan (TypedRange location _ _) = Just location
expressionSpan (Coerce location _ _) = Just location
expressionSpan (TypedLambda location _ _ _ _ _) = Just location
expressionSpan (Aggregate location _ _ _) = Just location
expressionSpan (SetIdentity location _ _ _) = Just location
expressionSpan (MetricBoundedSet location _ _) = Just location
expressionSpan (ExistentialSetPredicate location _ _ _ _ _) = Just location
expressionSpan (GuardedSet location _ _ _ _ _) = Just location
expressionSpan (GeneratedUnion location _ _ _ _) = Just location
expressionSpan (Negate location _ _) = Just location
expressionSpan (Index location _ _ _ _) = Just location
