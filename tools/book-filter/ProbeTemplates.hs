    , "  | .forallE name ty body bi =>"
    , "    let domain ← operatorNodes levelParams expectations ty"
    , "    withLocalDecl name bi ty fun x => do"
    , "      return domain ++ (← operatorNodes levelParams expectations (body.instantiate1 x))"
    , "  | .letE name ty value body _ =>"
    , "    -- Original context lets retain large proof values; only generated markers"
    , "    -- can contain instrumentation to inspect inside their values."
    , "    let isMarker := expectations.any (fun pair => pair.1 == name.toString)"
    , "    let mut found ← if isMarker then operatorNodes levelParams expectations value else pure #[]"
    , "    if isMarker then"
    , "      found := found.push <| Json.mkObj ["
    , "        (\"marker\", toJson name.toString), (\"elaborated\", ← operatorApplication value),"
    , "        (\"distanceRequirement\", ← distanceRequirement levelParams value),"
    , "        (\"inclusionRequirement\", ← inclusionRequirement levelParams value),"
    , "        (\"subtypeArgumentRequirement\", ← subtypeArgumentRequirement levelParams value),"
