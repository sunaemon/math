    , "  | .app f a => return (← operatorNodes levelParams expectations f) ++ (← operatorNodes levelParams expectations a)"
    , "  | .mdata _ body => operatorNodes levelParams expectations body"
    , "  | .proj _ _ body => operatorNodes levelParams expectations body"
    , "  | _ => return #[]"
