    , "private partial def operatorNodes (levelParams : List Name) (expectations : Array (String × Array String × Array (Nat × String) × String))"
    , "    (e : Expr) : TermElabM (Array Json) := do"
    , "  -- Elaboration can copy marked set expressions into generated proof arguments."
