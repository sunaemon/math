    , "        (\"summabilityRequirement\", ← summabilityRequirement levelParams value),"
    , "        (\"operands\", ← match expectations.find? (fun pair => pair.1 == name.toString) with"
    , "          | some (_, expected, _, _) => pure (toJson (← checkOperands value expected))"
    , "          | none => pure Json.null),"
    , "        (\"callee\", ← match expectations.find? (fun pair => pair.1 == name.toString) with"
    , "          | some (_, _, _, candidate) =>"
    , "            if candidate.isEmpty then pure Json.null else checkOperand value.getAppFn candidate"
    , "          | none => pure Json.null),"
