{-# LANGUAGE OverloadedStrings #-}

-- | Lean programs used by native proof-context generation.
module ContextTemplates where

import Data.Text (Text)
import qualified Data.Text as T

freshTemplate :: Text
freshTemplate =
  T.unlines
    [ ""
    , "private def FRESH (xs : Array Expr) (original : Name) : MetaM Name := do"
    , "  let used ← xs.mapM fun x => return (← x.fvarId!.getDecl).userName"
    , "  let original := if original.hasMacroScopes then"
    , "    Name.mkSimple (\"book_hyg_\" ++ toString xs.size) else original"
    , "  if !used.contains original then return original"
    , "  let mut name := Name.mkSimple (original.toString ++ \"_book_\" ++ toString xs.size)"
    , "  while used.contains name do"
    , "    name := Name.mkSimple (name.toString ++ \"_\")"
    , "  return name"
    ]

unfoldTemplate :: Text
unfoldTemplate =
  T.unlines
    [ ""
    , "private def UNFOLD (e : Expr) : MetaM (Expr × Json) := do"
    , "  let .const name levels := e.getAppFn | throwError \"Unfold step requires a constant-headed application\""
    , "  let info ← getConstInfo name"
    , "  let some value := info.value? (allowOpaque := true) | throwError \"Unfold step requires a definition or theorem proof\""
    , "  let specialized := mkAppN (value.instantiateLevelParams info.levelParams levels) e.getAppArgs"
    , "  return (specialized.headBeta, Json.mkObj ["
    , "    (\"declaration\", toJson name.toString), (\"signature\", toJson (reprStr info.type)),"
    , "    (\"body\", toJson (reprStr value))])"
    ]

inspectionTemplate :: Text
inspectionTemplate =
  T.unlines
    [ ""
    , "open Lean Meta Elab Command"
    , "set_option pp.universes false"
    , "set_option maxRecDepth 8192"
    , "set_option maxHeartbeats 0"
    , ""
    , "FRESH_DEFINITION"
    , "UNFOLD_DEFINITION"
    , "private def contextJson (xs : Array Expr) (origins : Array Name) : MetaM Json := do"
    , "  let mut rows := #[]"
    , "  for x in xs, origin in origins do"
    , "    let d ← x.fvarId!.getDecl"
    , "    let value ← match d.value? with"
    , "      | none => pure Json.null"
    , "      | some v => pure (toJson (← ppExpr v).pretty)"
    , "    rows := rows.push <| Json.mkObj ["
    , "      (\"name\", toJson d.userName.toString), (\"originalName\", toJson origin.toString),"
    , "      (\"instance\", toJson d.binderInfo.isInstImplicit),"
    , "      (\"type\", toJson (← ppExpr d.type).pretty),"
    , "      (\"value\", value)]"
    , "  return toJson rows"
    , ""
    , "private partial def visitProof (root : String) (wanted : String) (path : String)"
    , "    (xs : Array Expr) (origins : Array Name) (unfoldings : Array String)"
    , "    (emitted : IO.Ref (Array String)) (e : Expr) : MetaM Unit := do"
    , "  let pieces := wanted.splitOn \"::\""
    , "  let wantedPath := pieces.head!"
    , "  if pieces.length == 2 && path == wantedPath then"
    , "    return ← visitProof root pieces[1]! path xs origins unfoldings emitted e"
    , "  let exactPath := wantedPath == \"root\" || wantedPath.startsWith \"root.\""
    , "  if exactPath && path != wantedPath && !wantedPath.startsWith (path ++ \".\") then return"
    , "  if exactPath && (wantedPath == path ++ \".unfold\" || wantedPath.startsWith (path ++ \".unfold.\")) then"
    , "    let (expanded, dependency) ← unfoldContextStep e"
    , "    let name := e.getAppFn.constName!.toString"
    , "    unless (← emitted.get).contains name do"
    , "      logInfo m!\"BOOK_LEAN_EXPORT {dependency.compress}\""
    , "      emitted.modify (·.push name)"
    , "    return ← visitProof root wanted (path ++ \".unfold\") xs origins (unfoldings.push name) emitted expanded"
    , "  match e with"
    , "  | .lam name ty body bi =>"
    , "    let resolvedName ← freshContextName xs name"
    , "    withLocalDecl resolvedName bi ty fun x => do"
    , "      let ys := xs.push x"
    , "      if name.toString == wanted || path == wanted then"
    , "        logInfo m!\"BOOK_LEAN_EXPORT {(Json.mkObj ["
    , "          (\"declaration\", toJson (root ++ \"@\" ++ path)),"
    , "          (\"localName\", toJson name.toString), (\"unfoldings\", toJson unfoldings),"
    , "          (\"kind\", toJson \"lambda\"), (\"binders\", ← contextJson ys (origins.push name))]).compress}\""
    , "      if !exactPath || path != wanted then"
    , "        visitProof root wanted (path ++ \".body\") ys (origins.push name) unfoldings emitted (body.instantiate1 x)"
    , "  | .letE name ty value body _ =>"
    , "    let resolvedName ← freshContextName xs name"
    , "    withLetDecl resolvedName ty value fun x => do"
    , "      let ys := xs.push x"
    , "      if name.toString == wanted || path == wanted then"
    , "        logInfo m!\"BOOK_LEAN_EXPORT {(Json.mkObj ["
    , "          (\"declaration\", toJson (root ++ \"@\" ++ path)),"
    , "          (\"localName\", toJson name.toString), (\"unfoldings\", toJson unfoldings),"
    , "          (\"kind\", toJson \"let\"), (\"binders\", ← contextJson ys (origins.push name))]).compress}\""
    , "      if !exactPath || path != wanted then"
    , "        visitProof root wanted (path ++ \".body\") ys (origins.push name) unfoldings emitted (body.instantiate1 x)"
    , "    visitProof root wanted (path ++ \".value\") xs origins unfoldings emitted value"
    , "  | .app f a =>"
    , "    visitProof root wanted (path ++ \".fn\") xs origins unfoldings emitted f"
    , "    visitProof root wanted (path ++ \".arg\") xs origins unfoldings emitted a"
    , "  | .mdata _ body => visitProof root wanted (path ++ \".metadata\") xs origins unfoldings emitted body"
    , "  | .proj _ _ body => visitProof root wanted (path ++ \".projection\") xs origins unfoldings emitted body"
    , "  | _ => pure ()"
    ]

expressionTemplate :: Text
expressionTemplate =
  T.unlines
    [ ""
    , "open Lean Meta Elab Command"
    , "FRESH_DEFINITION"
    , "UNFOLD_DEFINITION"
    , "private partial def HELPER (steps : List String) (xs : Array Expr) (e : Expr)"
    , "    (action : Array Expr → TermElabM Expr) : TermElabM Expr := do"
    , "  match e, steps with"
    , "  | _, \"unfold\" :: rest =>"
    , "    let (expanded, _) ← UNFOLD e"
    , "    HELPER rest xs expanded action"
    , "  | .lam n ty _ bi, [] =>"
    , "    let resolvedName ← FRESH xs n"
    , "    withLocalDecl resolvedName bi ty fun x => action (xs.push x)"
    , "  | .lam n ty body bi, \"body\" :: rest =>"
    , "    let resolvedName ← FRESH xs n"
    , "    withLocalDecl resolvedName bi ty fun x => HELPER rest (xs.push x) (body.instantiate1 x) action"
    , "  | .letE n ty value _ _, [] =>"
    , "    let resolvedName ← FRESH xs n"
    , "    withLetDecl resolvedName ty value fun x => action (xs.push x)"
    , "  | .letE n ty value body _, \"body\" :: rest =>"
    , "    let resolvedName ← FRESH xs n"
    , "    withLetDecl resolvedName ty value fun x => HELPER rest (xs.push x) (body.instantiate1 x) action"
    , "  | .letE _ _ value _ _, \"value\" :: rest => HELPER rest xs value action"
    , "  | .app f _, \"fn\" :: rest => HELPER rest xs f action"
    , "  | .app _ a, \"arg\" :: rest => HELPER rest xs a action"
    , "  | .mdata _ body, \"metadata\" :: rest => HELPER rest xs body action"
    , "  | .proj _ _ body, \"projection\" :: rest => HELPER rest xs body action"
    , "  | _, _ => throwError \"Proof-context path does not reach a binder\""
    , "run_cmd liftTermElabM do"
    , "  let info ← getConstInfo ROOT.toName"
    , "  let some body := info.value? (allowOpaque := true) | throwError \"No original definition\""
    , "  let value ← HELPER STEPS #[] body fun xs => do"
    , "    let stx ← match Parser.runParserCategory (← getEnv) `term TERM with"
    , "      | .ok stx => pure stx"
    , "      | .error message => throwError \"Context term parse failed: {message}\""
    , "    let value ← Term.withoutErrToSorry <| Term.elabTerm stx none"
    , "    Term.synthesizeSyntheticMVarsNoPostponing"
    , "    let value ← instantiateMVars value"
    , "    if value.hasSorry || value.hasMVar then throwError \"Incomplete context term\""
    , "    mkLambdaFVars xs value (usedOnly := false) (usedLetOnly := false) (generalizeNondepLet := false)"
    , "  let type ← inferType value"
    , "  if value.hasFVar || type.hasFVar then throwError \"Context term escaped its binders\""
    , "  addDecl (.defnDecl {"
    , "    name := OUTPUT.toName, levelParams := info.levelParams,"
    , "    type := type, value := value, hints := .abbrev, safety := .safe })"
    ]

inspectionCommandTemplate :: Text
inspectionCommandTemplate =
  T.unlines
    [ ""
    , "run_cmd liftTermElabM do"
    , "  let root := ROOT"
    , "  let info ← getConstInfo root.toName"
    , "  let some body := info.value? (allowOpaque := true) | throwError \"Declaration has no proof/value\""
    , "  logInfo m!\"BOOK_LEAN_EXPORT {(Json.mkObj ["
    , "    (\"declaration\", toJson root),"
    , "    (\"signature\", toJson (reprStr info.type)),"
    , "    (\"body\", toJson (reprStr body))]).compress}\""
    , "  let emitted ← IO.mkRef (#[] : Array String)"
    , "  for wanted in [WANTED] do"
    , "    visitProof root wanted \"root\" #[] #[] #[] emitted body"
    ]
